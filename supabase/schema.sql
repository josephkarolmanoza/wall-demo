-- The existing Supabase table is public.posts with id, body, and created_at.
-- This adds post profile data, reactions, comments, and an idempotency key for sample posts.
alter table public.posts
  add column if not exists name text not null default 'Someone';

alter table public.posts
  add column if not exists seed_key text;

alter table public.posts
  add column if not exists avatar_url text;

alter table public.posts
  add column if not exists image_url text;

create unique index if not exists posts_seed_key_unique
  on public.posts (seed_key);

alter table public.posts enable row level security;
grant select, insert on public.posts to anon, authenticated;

do $$
declare
  posts_sequence regclass;
begin
  posts_sequence := pg_get_serial_sequence('public.posts', 'id');
  if posts_sequence is not null then
    execute format('grant usage, select on sequence %s to anon, authenticated', posts_sequence);
  end if;
end;
$$;

drop policy if exists "Wall posts are public to read" on public.posts;
create policy "Wall posts are public to read"
  on public.posts for select
  to anon, authenticated
  using (true);

drop policy if exists "Visitors can add short wall posts" on public.posts;
create policy "Visitors can add short wall posts"
  on public.posts for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 40
    and char_length(btrim(body)) <= 280
    and (char_length(btrim(body)) >= 1 or image_url is not null)
  );

create table if not exists public.post_likes (
  post_id uuid not null references public.posts(id) on delete cascade,
  visitor_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (post_id, visitor_id)
);

create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.posts(id) on delete cascade,
  visitor_id uuid not null,
  name text not null,
  body text not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  constraint post_comments_name_length check (char_length(btrim(name)) between 1 and 40),
  constraint post_comments_body_length check (char_length(btrim(body)) between 1 and 280)
);

alter table public.post_likes enable row level security;
alter table public.post_comments enable row level security;
grant select, insert, delete on public.post_likes to anon, authenticated;
grant select, insert on public.post_comments to anon, authenticated;
grant usage, select on sequence public.post_comments_id_seq to anon, authenticated;

drop policy if exists "Likes are public to read" on public.post_likes;
create policy "Likes are public to read"
  on public.post_likes for select
  to anon, authenticated
  using (true);

drop policy if exists "Visitors can like posts" on public.post_likes;
create policy "Visitors can like posts"
  on public.post_likes for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Visitors can remove likes" on public.post_likes;
create policy "Visitors can remove likes"
  on public.post_likes for delete
  to anon, authenticated
  using (true);

drop policy if exists "Comments are public to read" on public.post_comments;
create policy "Comments are public to read"
  on public.post_comments for select
  to anon, authenticated
  using (true);

drop policy if exists "Visitors can add comments" on public.post_comments;
create policy "Visitors can add comments"
  on public.post_comments for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 40
    and char_length(btrim(body)) between 1 and 280
  );

